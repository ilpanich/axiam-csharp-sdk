def prop(name: str) -> str:
    """``resource_type`` -> ``ResourceType``: a C# property is PascalCase."""
    return pascal(name)


def arg(name: str) -> str:
    """``resource_id`` -> ``resourceId``, ``@``-escaped if it is a keyword."""
    out = camel(name)
    return f"@{out}" if out in CS_KEYWORDS else out


def cs_type(schema: Any) -> str:
    """The C# type for ``schema``, without nullability."""
    if not schema:
        return "JsonElement"
    if "$ref" in schema:
        return pascal(schema["$ref"].split("/")[-1])
    inner = nullable_ref(schema)
    if inner:
        return pascal(inner)
    if "oneOf" in schema or "anyOf" in schema:
        return "JsonElement"

    kind = schema.get("type")
    if isinstance(kind, list):
        kind = next((k for k in kind if k != "null"), None)

    if kind == "string":
        if schema.get("format") == "uuid":
            return "Guid"
        if schema.get("format") == "date-time":
            return "DateTimeOffset"
        return "string"
    if kind == "integer":
        return "long" if schema.get("format") == "int64" else "int"
    if kind == "number":
        return "double"
    if kind == "boolean":
        return "bool"
    if kind == "array":
        return f"IReadOnlyList<{cs_type(schema.get('items') or {})}>"
    if kind == "object":
        return "JsonElement"
    return "JsonElement"


# Model type names that collide with a type the SDK already exports from another
