def build() -> dict[Path, str]:
    """Every file this generator owns, mapped to its current content."""
    files: dict[Path, str] = {}
    for path, body in emit_models().items():
        files[ROOT / path] = body
    for ns, nsdef in REGISTRY["namespaces"].items():
        files[ROOT / f"{API_DIR}/{pascal(ns)}Api.cs"] = emit_namespace(ns, nsdef)
    files[ROOT / f"{API_DIR}/ManagementApi.cs"] = emit_api()
    files[ROOT / f"{TEST_DIR}/ManagementSurfaceGeneratedTests.cs"] = emit_test()
    files[ROOT / f"{TEST_DIR}/ManagementSparseBodiesGeneratedTests.cs"] = emit_sparse_test()
    return files


def prune(files: dict[Path, str]) -> list[Path]:
    """Generated files on disk that this run no longer produces."""
    stale: list[Path] = []
    for directory in (MODELS_DIR, API_DIR, TEST_DIR):
        target = ROOT / directory
        if not target.exists():
            continue
        for path in sorted(target.glob("*.cs")):
            if path in files:
                continue
            if path.read_text().startswith("// <auto-generated>"):
                stale.append(path)
    return stale


def main() -> int:
    """Write the generated surface, or verify the committed copy is current."""
    PROJECTIONS.update(projection_map())
    check = "--check" in sys.argv
    files = build()
    stale = prune(files)

    if check:
        drifted = [p for p, body in files.items() if not p.exists() or p.read_text() != body]
        if drifted or stale:
            for path in sorted(drifted):
                print(f"DRIFT: {path.relative_to(ROOT)}", file=sys.stderr)
            for path in stale:
                print(f"STALE: {path.relative_to(ROOT)}", file=sys.stderr)
            print(
                f"\n{len(drifted)} file(s) differ and {len(stale)} are stale. The committed "
                "§27 surface is not what scripts/gen_management.py produces from the "
                "vendored management-registry.json and openapi.json.\nRun `python3 "
                "scripts/gen_management.py` and commit the result.",
                file=sys.stderr,
            )
            return 1
        print(f"OK: {len(files)} generated files are current "
              f"({REGISTRY['operation_count']} operations)")
        return 0

    for path in stale:
        path.unlink()
    for path, body in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body)
    print(f"wrote {len(files)} files: {REGISTRY['operation_count']} operations across "
          f"{len(REGISTRY['namespaces'])} namespaces"
          + (f"; pruned {len(stale)}" if stale else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
