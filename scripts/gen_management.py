def path_param_names(op: dict[str, Any]) -> list[str]:
    """This operation's path parameter names, in path order."""
    return [p["name"] for p in op["path_params"]]


def implicit_params(namespace: str, op: dict[str, Any]) -> set[str]:
    """Which of this operation's path params default from the client (§27.4 rule 3)."""
    out: set[str] = set()
    for param in path_param_names(op):
        if param == "org_id":
            out.add(param)
        elif param == "tenant_id" and namespace in IMPLICIT_TENANT_NAMESPACES:
            out.add(param)
    return out


def split_query(op: dict[str, Any]) -> tuple[list[str], list[str]]:
    """This operation's query parameter NAMES, split into paging and the rest."""
    names = [q["name"] for q in op["query_params"]]
    # ``search`` joins them on a paginated operation (CONTRACT §27.4 rule 4): the
    # term is part of which page this is, and putting it on the page request
    # rather than on each of the twenty generated ``ListAsync`` methods is what
    # makes ``CollectPagesAsync`` carry it across the whole walk instead of
    # filtering only the first request.
    #
    # The ``paginated`` guard matters. A *non*-paginated operation that grew a
    # ``search`` parameter would have no ``PageRequest`` to carry it, so it keeps
    # its own argument -- none exists in the registry today, and this is what
    # keeps that from silently dropping the parameter if one ever does.
    owned = ("offset", "limit", "search") if op["paginated"] else ("offset", "limit")
    paging = [n for n in names if n in owned]
    other = [n for n in names if n not in owned]
    return paging, other


def operation_params(namespace: str, op: dict[str, Any]) -> list[dict[str, str]]:
    """The C# parameter list for one generated operation, in order."""
    implicit = implicit_params(namespace, op)
    params: list[dict[str, str]] = []
    for param in path_param_names(op):
        if param in implicit:
            continue
        params.append({
            "name": arg(param), "type": "Guid", "default": "",
            "doc": f"the {param.replace('_', ' ')} to address",
        })
    if op["request_schema"]:
        params.append({
            "name": "body", "type": pascal(op["request_schema"].lstrip("[]")), "default": "",
            "doc": "the request body",
        })
    _, other = split_query(op)
    for query in other:
        params.append({
            "name": arg(query), "type": "string?", "default": " = null",
            "doc": f"the optional {query.replace('_', ' ')} filter, or <c>null</c> to omit it",
        })
    if op["paginated"]:
        params.append({
            "name": "page", "type": "PageRequest?", "default": " = null",
            "doc": "where to start and how many to ask for, or <c>null</c> for the server's default",
        })
    params.append({
        "name": "cancellationToken", "type": "CancellationToken", "default": " = default",
        "doc": "cancels the request",
    })
    return params


def response_cs(op: dict[str, Any]) -> tuple[str, str]:
    """The declared return type, and how the body is decoded into it.

    Driven by the registry's ``response.kind``, which is the authoritative statement of
    the shape. The ``schema`` field never carries an ``[]`` prefix, so inferring
    array-ness from the name silently turns all thirteen bare-array reads into single
    objects -- the exact confusion §27.4 rule 4 exists to prevent.
    """
    kind, schema = op["response"]["kind"], op["response"]["schema"]
    if kind == "none" or not schema:
        return "", "unit"
    model = pascal(schema)
    if kind == "page":
        return f"Page<{model}>", "page"
    if kind == "array":
        return f"IReadOnlyList<{model}>", "list"
    return model, "one"


def spec_description(op: dict[str, Any]) -> str | None:
    """The prose openapi.json carries for this route, if any."""
    entry = SPEC.get("paths", {}).get(op["path"], {}).get(op["method"].lower())
    if not isinstance(entry, dict):
        return None
    text = entry.get("description")
    return escape(text) if text else None


def operation_doc(op: dict[str, Any], method_name: str) -> str:
    """The doc body for one generated operation."""
    prose = spec_description(op)
    route = f"<c>{op['method']} {escape(op['path'])}</c>"
    lines = [f"{prose}\n\nIssues {route}." if prose else f"Issues {route}."]
    if op["paginated"]:
        lines.append(
            f"\n\nPaginated: Total on the returned page is the size of the WHOLE set, not of "
            f"this page (&#167;27.4 rule 4). Use {method_name}AllAsync(...) to walk every page.")
    if op["update_style"] == "sparse":
        lines.append(
            "\n\nA SPARSE update: the properties you leave unset are omitted from the wire "
            "body entirely and left unchanged (&#167;27.4 rule 5).")
    elif op["update_style"] == "replace":
        lines.append(
            "\n\nA REPLACEMENT, not a patch: every field of the body is written, so read the "
            "current value first and carry over the parts you mean to keep "
            "(&#167;27.4 rule 5).")
    if op["method"] != "GET":
        lines.append(
            "\n\nNot retried: &#167;27.4 rule 8 makes every write on this surface "
            "single-shot, including the ones that look idempotent.")
    return "".join(lines)


def emit_operation(namespace: str, opname: str, op: dict[str, Any]) -> list[str]:
    """One generated async method on a namespace handle."""
    canonical = f"{namespace}.{opname}"
    method_name = pascal(opname)
    params = operation_params(namespace, op)
    ret, shape = response_cs(op)
    implicit = implicit_params(namespace, op)

    tags = [f'<param name="{p["name"].lstrip("@")}">{p["doc"]}.</param>' for p in params]
    tags.append(
        '<returns>the page of results</returns>' if shape == "page"
        else '<returns>a task that completes when the server has answered</returns>' if shape == "unit"
        else '<returns>the server response</returns>')

    lines = xmldoc(operation_doc(op, method_name), "    ", tags)
    signature = ", ".join(f'{p["type"]} {p["name"]}{p["default"]}' for p in params)
    declared = "Task" if shape == "unit" else f"Task<{ret}>"
    lines.append(f"    public async {declared} {method_name}Async({signature})")
    lines.append("    {")

    for param in sorted(implicit):
        resolver = "ResolveOrg" if param == "org_id" else "ResolveTenant"
        lines.append(f'        Guid {arg(param)} = ManagementSupport.{resolver}('
                     f'_transport, _scope, "{canonical}");')

    path = op["path"]
    for param in path_param_names(op):
        path = path.replace("{" + param + "}", "{" + arg(param) + "}")
    lines.append(f'        string path = $"{path}";')

    _, other = split_query(op)
    if other or op["paginated"]:
        if other:
            entries = ", ".join(f'["{q}"] = {arg(q)}' for q in other)
            base = ("new Dictionary<string, string?>(StringComparer.Ordinal) { "
                    + entries + " }")
        else:
            base = "null"
        if op["paginated"]:
            lines.append(f"        Dictionary<string, string?> query = "
                         f"ManagementSupport.PageQuery({base}, page);")
        else:
            lines.append(f"        Dictionary<string, string?> query = {base};")

    if op["request_schema"]:
        lines.append(f'        string payload = ManagementSupport.EncodeBody("{canonical}", body);')

    lines.append(f"        {'JsonElement? node = ' if shape != 'unit' else ''}"
                 "await _transport.SendAsync(")
    lines.append(f'            "{canonical}",')
    lines.append(f'            HttpMethod.{op["method"].capitalize() if op["method"] != "DELETE" else "Delete"},')
    lines.append(f'            "{op["path"]}",')
    lines.append("            path,")
    lines.append("            " + ("query," if (other or op["paginated"]) else "null,"))
    lines.append("            " + ("payload," if op["request_schema"] else "null,"))
    lines.append("            cancellationToken).ConfigureAwait(false);")

    if shape == "page":
        model = ret[len("Page<"):-1]
        lines.append(f'        return ManagementSupport.DecodePage<{model}>("{canonical}", node);')
    elif shape == "list":
        model = ret[len("IReadOnlyList<"):-1]
        lines.append(f'        return ManagementSupport.DecodeList<{model}>("{canonical}", node);')
    elif shape == "one":
        lines.append(f'        return ManagementSupport.Decode<{ret}>("{canonical}", node);')
    lines.append("    }")

    if op["paginated"]:
        lead = [p for p in params if p["name"] not in ("page", "cancellationToken")]
        sig = ", ".join(f'{p["type"]} {p["name"]}{p["default"]}' for p in lead)
        sig = ((sig + ", ") if sig else "") + \
            "PageRequest? start = null, CancellationToken cancellationToken = default"
        call = ", ".join(p["name"].lstrip("@") + ": " + p["name"] for p in lead)
        call = ((call + ", ") if call else "") + "page: window, cancellationToken: cancellationToken"
        model = ret[len("Page<"):-1]
        all_tags = [f'<param name="{p["name"].lstrip("@")}">{p["doc"]}.</param>' for p in lead]
        all_tags.append('<param name="start">the first window to request, or <c>null</c> '
                        'for the server\'s default.</param>')
        all_tags.append('<param name="cancellationToken">cancels the walk.</param>')
        all_tags.append("<returns>every item, in the server's order</returns>")
        lines.append("")
        lines.extend(xmldoc(
            f"Walks {method_name}Async to exhaustion and returns every item "
            f"(&#167;27.4 rule 4).\n\nStops on an empty page even when the server's Total "
            f"disagrees, so a misreporting server costs one wasted request rather than an "
            f"unbounded loop.", "    ", all_tags))
        lines.append(f"    public Task<IReadOnlyList<{model}>> {method_name}AllAsync({sig}) =>")
        lines.append(f"        ManagementSupport.CollectPagesAsync(start, window =>")
        lines.append(f"            {method_name}Async({call}));")
    return lines


