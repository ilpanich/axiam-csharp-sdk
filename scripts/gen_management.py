def sparse_models() -> list[tuple[str, list[dict[str, Any]]]]:
    """Every schema whose properties are all optional -- the sparse bodies."""
    secrets = sensitive_map()
    out: list[tuple[str, list[dict[str, Any]]]] = []
    for name in schema_closure():
        schema = SCHEMAS[name]
        if "enum" in schema and schema.get("type") == "string":
            continue
        if discriminated(schema):
            continue
        fields, required, _ = field_list(name, secrets.get(name, set()))
        if fields and not required:
            out.append((name, fields))
    return out


def sparse_literal(schema: Any, wire: str, secrets: set[str]) -> str:
    """A NON-null C# literal for a sparse property.

    ``cs_literal`` is allowed to answer ``null`` -- it fills optional components of a
    request the surface test only needs to be well-formed. Here null is the one answer
    that cannot be used: the whole assertion is that a property which WAS set reaches
    the wire, and an unset one is omitted by design.
    """
    if wire in secrets:
        return 'Sensitive<string>.Wrap("example")'
    ref = schema["$ref"].split("/")[-1] if "$ref" in schema else nullable_ref(schema)
    if ref and ref in SCHEMAS:
        return literal_for(ref, set())
    rendered = cs_type(schema)
    if rendered.startswith("IReadOnlyList<"):
        return f"Array.Empty<{rendered[len('IReadOnlyList<'):-1]}>()"
    return {
        "Guid": "ExampleId",
        "DateTimeOffset": f'DateTimeOffset.Parse("{EXAMPLE_TIME}", CultureInfo.InvariantCulture)',
        "string": '"example"',
        "long": "1L",
        "int": "1",
        "double": "1.0",
        "bool": "true",
        "JsonElement": 'JsonDocument.Parse("{}").RootElement',
    }[rendered]


