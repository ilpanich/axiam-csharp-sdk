#!/usr/bin/env python3
"""Generate the CONTRACT §27 management surface for the C# SDK.

Reads ``management-registry.json`` (the 147 operations across 24 namespaces,
maintained in ``ilpanich/axiam`` and vendored here) plus ``openapi.json`` for the
schemas those operations carry, and writes:

- ``Axiam.Sdk/Management/Models/*.cs`` — one ``sealed record``, enum or polymorphic
  base per request and response type;
- ``Axiam.Sdk/Management/<Namespace>Api.cs`` — one namespace handle per namespace;
- ``Axiam.Sdk/Management/ManagementApi.cs`` — the accessors;
- ``tests/Axiam.Sdk.Tests/Management/ManagementSurfaceGeneratedTests.cs``
- ``tests/Axiam.Sdk.Tests/Management/ManagementSparseBodiesGeneratedTests.cs``
  — one conformance case per operation, plus the §27.9 assertion that all 147 are
  reached.

Run with ``--check`` to verify the committed output is current; that is what CI runs,
so a registry change that is not regenerated fails the build rather than shipping a
surface that disagrees with the contract.

Everything this emits must satisfy the project's documentation gate: ``Axiam.Sdk.csproj``
promotes ``CS1591`` ("missing XML doc comment on publicly visible member") to an error,
so every public type, member, parameter and return value needs a doc comment and every
description carried over from ``openapi.json`` has to be XML-escaped on the way in.

§27.4 rule 5 ("an unset field is *absent*, not null") is satisfied by nullable
properties with ``= null`` defaults plus ``JsonIgnoreCondition.WhenWritingNull`` on the
request writer, so there are no builders to generate.
"""

